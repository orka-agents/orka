// Package envelopegen renders the storage client's write envelope decorators
// from the provider interfaces and the method catalog in pkg/storage/v1.
//
// Each decorator embeds one provider and overrides every method the catalog
// classifies as a write, so the write runs through the storage client's
// operation runner. Reads and administrative methods are promoted from the
// embedded provider unchanged.
package envelopegen

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"path"
	"reflect"
	"sort"
	"strings"

	storagev1 "github.com/orka-agents/orka/pkg/storage/v1"
)

// Header starts the generated file.
const Header = "// Code generated by envelopegen. DO NOT EDIT.\n"

// decorator is one generated decorator type.
type decorator struct {
	typeName     string
	field        string
	iface        reflect.Type
	contract     string
	contractExpr string
}

var decorators = []decorator{
	{
		typeName: "envelopedState", field: "StateProvider",
		iface:    reflect.TypeFor[storagev1.StateProvider](),
		contract: storagev1.StateContract, contractExpr: "storagev1.StateContract",
	},
	{
		typeName: "envelopedArtifacts", field: "ArtifactProvider",
		iface:    reflect.TypeFor[storagev1.ArtifactProvider](),
		contract: storagev1.ArtifactsContract, contractExpr: "storagev1.ArtifactsContract",
	},
}

var (
	contextType = reflect.TypeFor[context.Context]()
	errorType   = reflect.TypeFor[error]()
	fenceType   = reflect.TypeFor[storagev1.ControllerEpochFence]()
)

// Generate returns the formatted source of the decorators for package pkg.
func Generate(pkg string) ([]byte, error) {
	g := &generator{imports: map[string]string{}}
	g.imports["context"] = "context"
	g.imports["github.com/orka-agents/orka/pkg/storage/v1"] = "storagev1"
	var body bytes.Buffer
	for _, d := range decorators {
		if err := g.decorator(&body, d); err != nil {
			return nil, err
		}
	}
	var out bytes.Buffer
	out.WriteString(Header)
	fmt.Fprintf(&out, "\npackage %s\n\nimport (\n", pkg)
	paths := make([]string, 0, len(g.imports))
	for importPath := range g.imports {
		paths = append(paths, importPath)
	}
	// Standard library imports first, as goimports groups them.
	sort.Slice(paths, func(i, j int) bool {
		iStd, jStd := isStandard(paths[i]), isStandard(paths[j])
		if iStd != jStd {
			return iStd
		}
		return paths[i] < paths[j]
	})
	for i, importPath := range paths {
		if i > 0 && isStandard(paths[i-1]) && !isStandard(importPath) {
			out.WriteString("\n")
		}
		alias := g.imports[importPath]
		if alias == path.Base(importPath) {
			fmt.Fprintf(&out, "\t%q\n", importPath)
		} else {
			fmt.Fprintf(&out, "\t%s %q\n", alias, importPath)
		}
	}
	out.WriteString(")\n")
	out.Write(body.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated decorators: %w", err)
	}
	return formatted, nil
}

func isStandard(importPath string) bool {
	first, _, _ := strings.Cut(importPath, "/")
	return !strings.Contains(first, ".")
}

type generator struct {
	imports map[string]string // import path to its name in the file
}

func (g *generator) qualifier(importPath string) (string, error) {
	if alias, ok := g.imports[importPath]; ok {
		return alias, nil
	}
	alias := path.Base(importPath)
	for other, used := range g.imports {
		if used == alias {
			return "", fmt.Errorf("imports %q and %q share the name %s", importPath, other, alias)
		}
	}
	g.imports[importPath] = alias
	return alias, nil
}

// typeString renders t as Go source and records the imports it needs.
func (g *generator) typeString(t reflect.Type) (string, error) {
	if t.Name() != "" {
		if t.PkgPath() == "" {
			if t.Kind() == reflect.Uint8 {
				return "byte", nil
			}
			return t.Name(), nil
		}
		alias, err := g.qualifier(t.PkgPath())
		if err != nil {
			return "", err
		}
		return alias + "." + t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Pointer:
		elem, err := g.typeString(t.Elem())
		return "*" + elem, err
	case reflect.Slice:
		elem, err := g.typeString(t.Elem())
		return "[]" + elem, err
	case reflect.Array:
		elem, err := g.typeString(t.Elem())
		return fmt.Sprintf("[%d]%s", t.Len(), elem), err
	case reflect.Map:
		key, err := g.typeString(t.Key())
		if err != nil {
			return "", err
		}
		elem, err := g.typeString(t.Elem())
		return "map[" + key + "]" + elem, err
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any", nil
		}
	}
	return "", fmt.Errorf("unsupported parameter type %s", t)
}

func (g *generator) decorator(out *bytes.Buffer, d decorator) error {
	methods := make([]reflect.Method, 0, d.iface.NumMethod())
	for method := range d.iface.Methods() {
		info, ok := storagev1.LookupMethod(method.Name)
		if !ok {
			return fmt.Errorf("%s.%s is missing from the method catalog", d.iface, method.Name)
		}
		if info.Kind != storagev1.MethodWrite {
			continue
		}
		// A write every contract part serves, such as AdvanceWriteWatermark,
		// runs under the fence of the decorated provider's own dataset.
		if info.Contract != "" && info.Contract != d.contract {
			return fmt.Errorf("%s.%s is a %s write, not a %s write", d.iface, method.Name, info.Contract, d.contract)
		}
		methods = append(methods, method)
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name < methods[j].Name })
	for _, method := range methods {
		if err := g.method(out, d, method); err != nil {
			return fmt.Errorf("%s.%s: %w", d.iface, method.Name, err)
		}
	}
	return nil
}

func (g *generator) method(out *bytes.Buffer, d decorator, method reflect.Method) error {
	fn := method.Type
	if fn.NumIn() == 0 || fn.In(0) != contextType {
		return fmt.Errorf("the first parameter is not a context.Context")
	}
	if fn.NumOut() == 0 || fn.Out(fn.NumOut()-1) != errorType {
		return fmt.Errorf("the last result is not an error")
	}
	var params, names, callArgs []string
	fence := ""
	for i := 1; i < fn.NumIn(); i++ {
		in := fn.In(i)
		name := fmt.Sprintf("a%d", i)
		typeName, err := g.typeString(in)
		if err != nil {
			return err
		}
		callArg := name
		if fn.IsVariadic() && i == fn.NumIn()-1 {
			elem, err := g.typeString(in.Elem())
			if err != nil {
				return err
			}
			typeName = "..." + elem
			callArg = name + "..."
		}
		params = append(params, name+" "+typeName)
		names = append(names, name)
		callArgs = append(callArgs, callArg)
		if explicit := explicitFence(name, in); explicit != "" {
			if fence != "" {
				return fmt.Errorf("more than one parameter carries a controller epoch fence")
			}
			fence = explicit
		}
	}
	var results, resultNames []string
	for i := range fn.NumOut() - 1 {
		typeName, err := g.typeString(fn.Out(i))
		if err != nil {
			return err
		}
		results = append(results, typeName)
		resultNames = append(resultNames, fmt.Sprintf("r%d", i))
	}

	call := fmt.Sprintf("p.%s.%s(%s)", d.field, method.Name, strings.Join(append([]string{"ctx"}, callArgs...), ", "))
	fenceField := ""
	if fence != "" {
		fenceField = ", fence: " + fence
	}
	writeCall := fmt.Sprintf("writeCall{method: %q, contract: %s, args: []any{%s}%s}",
		method.Name, d.contractExpr, strings.Join(names, ", "), fenceField)
	signature := fmt.Sprintf("func (p %s) %s(%s)", d.typeName, method.Name,
		strings.Join(append([]string{"ctx context.Context"}, params...), ", "))

	out.WriteString("\n")
	if len(results) == 0 {
		fmt.Fprintf(out, "%s error {\n", signature)
		fmt.Fprintf(out, "\treturn p.ops.run(ctx, %s, func(ctx context.Context) error {\n", writeCall)
		fmt.Fprintf(out, "\t\treturn %s\n\t})\n}\n", call)
		return nil
	}
	fmt.Fprintf(out, "%s (%s, error) {\n", signature, strings.Join(results, ", "))
	for i, result := range results {
		fmt.Fprintf(out, "\tvar r%d %s\n", i, result)
	}
	fmt.Fprintf(out, "\terr := p.ops.run(ctx, %s, func(ctx context.Context) error {\n", writeCall)
	fmt.Fprintf(out, "\t\tvar err error\n\t\t%s, err = %s\n\t\treturn err\n\t})\n", strings.Join(resultNames, ", "), call)
	fmt.Fprintf(out, "\treturn %s, err\n}\n", strings.Join(resultNames, ", "))
	return nil
}

// explicitFence returns the expression for the controller epoch fence that
// parameter name carries, as the parameter itself or as the Fence field of a
// request, or "" when it carries none.
func explicitFence(name string, t reflect.Type) string {
	if t == fenceType {
		return "&" + name
	}
	if t.Kind() == reflect.Struct {
		if field, ok := t.FieldByName("Fence"); ok && field.Type == fenceType && len(field.Index) == 1 {
			return "&" + name + ".Fence"
		}
	}
	return ""
}

// Command wrappergen writes wrappers_gen.go for package storagefault. Each
// generated method passes one provider call through the fault injector, so
// every method of the storage contract and of the embedded families can be
// failed, delayed, held or counted without hand-written delegation.
//
// Run it with go generate in internal/storageclient/storagefault. A test in
// this package fails when the committed file differs from its output.
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path"
	"reflect"
	"slices"
	"strings"

	"github.com/orka-agents/orka/internal/storageclient"
	storagev1 "github.com/orka-agents/orka/pkg/storage/v1"
)

const storagev1Path = "github.com/orka-agents/orka/pkg/storage/v1"

// importNames gives the generated file's name for each package it imports.
// Other packages use the last element of their path.
var importNames = map[string]string{
	storagev1Path: "storagev1",
}

func main() {
	output := flag.String("o", "wrappers_gen.go", "file to write")
	flag.Parse()
	source, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "wrappergen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, source, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "wrappergen:", err)
		os.Exit(1)
	}
}

// wrapper describes one generated wrapper type.
type wrapper struct {
	// typeName is the wrapper's type in package storagefault.
	typeName string
	// inner is the field holding the wrapped provider.
	inner string
	// methods are the methods to generate, sorted by name.
	methods []reflect.Method
	// contract returns the Go expression naming the contract of a call.
	contract func(method string) string
}

// generate returns the formatted source of wrappers_gen.go.
func generate() ([]byte, error) {
	stateType := reflect.TypeFor[storagev1.StateProvider]()
	artifactType := reflect.TypeFor[storagev1.ArtifactProvider]()
	artifactStoreType := reflect.TypeFor[storagev1.ArtifactStore]()
	embeddedType := reflect.TypeFor[storageclient.EmbeddedStore]()

	// Describe is written by hand, because its faults also rewrite what it
	// reports.
	handWritten := []string{"Describe"}
	wrappers := []wrapper{
		{
			typeName: "stateProvider",
			inner:    "inner",
			methods:  methodsOf(stateType, handWritten),
			contract: func(string) string { return "p.contract" },
		},
		{
			typeName: "artifactProvider",
			inner:    "inner",
			methods:  methodsOf(artifactType, handWritten),
			contract: func(string) string { return "p.contract" },
		},
		{
			// The embedded store reaches its state.v1 methods, Describe and
			// HealthCheck through its embedded stateProvider, so it only adds
			// the artifact methods and the embedded families. The embedded
			// families hold state records.
			typeName: "embeddedStore",
			inner:    "store",
			methods:  methodsOf(embeddedType, append(names(stateType), handWritten...)),
			contract: func(method string) string {
				if _, ok := artifactStoreType.MethodByName(method); ok {
					return "storagev1.ArtifactsContract"
				}
				return "storagev1.StateContract"
			},
		},
	}

	g := &generator{imports: map[string]string{}}
	var body bytes.Buffer
	for _, w := range wrappers {
		for _, method := range w.methods {
			if err := g.method(&body, w, method); err != nil {
				return nil, fmt.Errorf("%s.%s: %w", w.typeName, method.Name, err)
			}
		}
	}

	var file bytes.Buffer
	file.WriteString("// Code generated by wrappergen; DO NOT EDIT.\n\npackage storagefault\n\nimport (\n")
	paths := make([]string, 0, len(g.imports))
	for importPath := range g.imports {
		paths = append(paths, importPath)
	}
	// Standard library packages come first, as goimports groups them.
	slices.SortFunc(paths, func(a, b string) int {
		if standardA, standardB := isStandard(a), isStandard(b); standardA != standardB {
			if standardA {
				return -1
			}
			return 1
		}
		return strings.Compare(a, b)
	})
	for i, importPath := range paths {
		if i > 0 && isStandard(paths[i-1]) && !isStandard(importPath) {
			file.WriteString("\n")
		}
		if name := g.imports[importPath]; name != path.Base(importPath) {
			fmt.Fprintf(&file, "\t%s %q\n", name, importPath)
		} else {
			fmt.Fprintf(&file, "\t%q\n", importPath)
		}
	}
	file.WriteString(")\n")
	file.Write(body.Bytes())
	return format.Source(file.Bytes())
}

// isStandard reports whether importPath names a standard library package,
// whose first path element has no dot.
func isStandard(importPath string) bool {
	first, _, _ := strings.Cut(importPath, "/")
	return !strings.Contains(first, ".")
}

// methodsOf returns the methods of iface, sorted by name, without the methods
// named in skip.
func methodsOf(iface reflect.Type, skip []string) []reflect.Method {
	var methods []reflect.Method
	for method := range iface.Methods() {
		if !slices.Contains(skip, method.Name) {
			methods = append(methods, method)
		}
	}
	return methods
}

// names returns the names of the methods of iface.
func names(iface reflect.Type) []string {
	var result []string
	for method := range iface.Methods() {
		result = append(result, method.Name)
	}
	return result
}

type generator struct {
	// imports maps each imported package path to its name in the file.
	imports map[string]string
}

var (
	contextType = reflect.TypeFor[context.Context]()
	errorType   = reflect.TypeFor[error]()
)

// method writes one wrapper method. Every provider method takes a context
// first and returns an error last; the generator refuses any other shape,
// because the injector needs both.
func (g *generator) method(out *bytes.Buffer, w wrapper, method reflect.Method) error {
	signature := method.Type
	if signature.NumIn() == 0 || signature.In(0) != contextType {
		return fmt.Errorf("the first parameter is not a context.Context")
	}
	if signature.NumOut() == 0 || signature.Out(signature.NumOut()-1) != errorType {
		return fmt.Errorf("the last result is not an error")
	}
	g.use("context", "context")

	params := []string{"ctx context.Context"}
	args := []string{"ctx"}
	for i := 1; i < signature.NumIn(); i++ {
		name := fmt.Sprintf("a%d", i)
		paramType := signature.In(i)
		if signature.IsVariadic() && i == signature.NumIn()-1 {
			elem, err := g.typeName(paramType.Elem())
			if err != nil {
				return err
			}
			params = append(params, name+" ..."+elem)
			args = append(args, name+"...")
			continue
		}
		typeName, err := g.typeName(paramType)
		if err != nil {
			return err
		}
		params = append(params, name+" "+typeName)
		args = append(args, name)
	}
	results := make([]string, signature.NumOut()-1)
	resultTypes := make([]string, signature.NumOut())
	for i := range signature.NumOut() {
		typeName, err := g.typeName(signature.Out(i))
		if err != nil {
			return err
		}
		resultTypes[i] = typeName
		if i < len(results) {
			results[i] = fmt.Sprintf("r%d", i)
		}
	}
	resultList := resultTypes[0]
	if len(resultTypes) > 1 {
		resultList = "(" + strings.Join(resultTypes, ", ") + ")"
	}

	call := fmt.Sprintf("p.%s.%s(%s)", w.inner, method.Name, strings.Join(args, ", "))
	fmt.Fprintf(out, "\nfunc (p *%s) %s(%s) %s {\n", w.typeName, method.Name, strings.Join(params, ", "), resultList)
	if len(results) == 0 {
		fmt.Fprintf(out, "\t_, err := p.injector.call(ctx, %s, %q, func(ctx context.Context) error {\n", w.contract(method.Name), method.Name)
		fmt.Fprintf(out, "\t\treturn %s\n\t})\n\treturn err\n}\n", call)
		return nil
	}
	for i, result := range results {
		fmt.Fprintf(out, "\tvar %s %s\n", result, resultTypes[i])
	}
	fmt.Fprintf(out, "\tinjected, err := p.injector.call(ctx, %s, %q, func(ctx context.Context) (err error) {\n", w.contract(method.Name), method.Name)
	fmt.Fprintf(out, "\t\t%s, err = %s\n\t\treturn err\n\t})\n", strings.Join(results, ", "), call)
	// An injected outcome replaces the provider's, including any results the
	// provider returned before its response was lost.
	out.WriteString("\tif injected {\n")
	zeros := make([]string, len(results))
	for i := range results {
		zeros[i] = fmt.Sprintf("z%d", i)
		fmt.Fprintf(out, "\t\tvar %s %s\n", zeros[i], resultTypes[i])
	}
	fmt.Fprintf(out, "\t\treturn %s, err\n\t}\n", strings.Join(zeros, ", "))
	fmt.Fprintf(out, "\treturn %s, err\n}\n", strings.Join(results, ", "))
	return nil
}

// use records an import of the package named packageName and returns its
// name in the file.
func (g *generator) use(importPath, packageName string) string {
	if name, ok := g.imports[importPath]; ok {
		return name
	}
	name, ok := importNames[importPath]
	if !ok {
		name = packageName
	}
	g.imports[importPath] = name
	return name
}

// typeName returns the Go source for t as the generated file refers to it.
func (g *generator) typeName(t reflect.Type) (string, error) {
	if t.Name() != "" {
		if strings.Contains(t.Name(), "[") {
			return "", fmt.Errorf("generic type %s is not supported", t)
		}
		if t.PkgPath() == "" {
			return t.Name(), nil
		}
		// reflect names a type by its package's name, which can differ from
		// the last element of its import path, as harnessv2 does.
		packageName := strings.TrimSuffix(t.String(), "."+t.Name())
		name := g.use(t.PkgPath(), packageName)
		for other, otherName := range g.imports {
			if other != t.PkgPath() && otherName == name {
				return "", fmt.Errorf("packages %s and %s would both be imported as %s; add a name to importNames", other, t.PkgPath(), name)
			}
		}
		return name + "." + t.Name(), nil
	}
	switch t.Kind() {
	case reflect.Pointer, reflect.Slice:
		elem, err := g.typeName(t.Elem())
		if err != nil {
			return "", err
		}
		if t.Kind() == reflect.Pointer {
			return "*" + elem, nil
		}
		return "[]" + elem, nil
	case reflect.Array:
		elem, err := g.typeName(t.Elem())
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("[%d]%s", t.Len(), elem), nil
	case reflect.Map:
		key, err := g.typeName(t.Key())
		if err != nil {
			return "", err
		}
		elem, err := g.typeName(t.Elem())
		if err != nil {
			return "", err
		}
		return "map[" + key + "]" + elem, nil
	case reflect.Func:
		return g.funcType(t)
	case reflect.Interface:
		if t.NumMethod() == 0 {
			return "any", nil
		}
	case reflect.Struct:
		if t.NumField() == 0 {
			return "struct{}", nil
		}
	}
	return "", fmt.Errorf("unnamed type %s is not supported", t)
}

// funcType returns the Go source for the function type t.
func (g *generator) funcType(t reflect.Type) (string, error) {
	params := make([]string, t.NumIn())
	for i := range t.NumIn() {
		in := t.In(i)
		if t.IsVariadic() && i == t.NumIn()-1 {
			elem, err := g.typeName(in.Elem())
			if err != nil {
				return "", err
			}
			params[i] = "..." + elem
			continue
		}
		name, err := g.typeName(in)
		if err != nil {
			return "", err
		}
		params[i] = name
	}
	results := make([]string, t.NumOut())
	for i := range t.NumOut() {
		name, err := g.typeName(t.Out(i))
		if err != nil {
			return "", err
		}
		results[i] = name
	}
	source := "func(" + strings.Join(params, ", ") + ")"
	switch len(results) {
	case 0:
		return source, nil
	case 1:
		return source + " " + results[0], nil
	default:
		return source + " (" + strings.Join(results, ", ") + ")", nil
	}
}

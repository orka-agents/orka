func TestDeleteRemovesOnlyTargetedComments(t *testing.T) {
	root := newRepo(t)
	for name, body := range map[string]string{"demo.go": goSource, "s.sh": shellSource} {
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	var targets []Target
	for _, name := range []string{"demo.go", "s.sh"} {
		comments, err := Scan(root, name)
		if err != nil {
			t.Fatal(err)
		}
		for _, c := range comments {
			targets = append(targets, Target{File: c.File, Line: c.Line})
		}
	}
	if err := Delete(root, targets); err != nil {
		t.Fatal(err)
	}
	keeps := map[string][]string{
		"demo.go": {"Copyright", "//go:generate", "// +kubebuilder:object:root=true", "Deprecated: use New.",
			"//nolint:ineffassign"},
		"s.sh": {"# shellcheck disable=SC2016", "#not a comment", "# heredoc body", "# nested heredoc body",
			"echo done\n"},
	}
	for name, want := range keeps {
		left, err := Scan(root, name)
		if err != nil || len(left) != 0 {
			t.Fatalf("%s still has %q (%v)", name, texts(left), err)
		}
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			t.Fatal(err)
		}
		for _, keep := range want {
			if !strings.Contains(string(data), keep) {
				t.Errorf("%s lost %q:\n%s", name, keep, data)
			}
		}
	}
	if err := Delete(root, []Target{{File: "demo.go", Line: 1}}); err == nil {
		t.Fatal("deleting a license header should fail")
	}
}


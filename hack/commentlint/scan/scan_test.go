func TestDeletionAfterContinuationIsRefused(t *testing.T) {
	root := newRepo(t)
	src := "shopt -s expand_aliases\nalias greet='echo ok'; \\\n# comment\ngreet\n"
	if err := os.WriteFile(filepath.Join(root, "a.sh"), []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := Delete(root, []Target{{File: "a.sh", Line: 3}}); err == nil {
		t.Fatal("deleting a comment after a continuation should be refused")
	}
	aliased := "shopt -s expand_aliases\nalias emit='cat <<EOF'\nemit\n# payload\nEOF\n"
	if err := os.WriteFile(filepath.Join(root, "b.sh"), []byte(aliased), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := Delete(root, []Target{{File: "b.sh", Line: 4}}); err == nil {
		t.Fatal("deleting comments in a script that expands aliases should be refused")
	}
	posix := "#!/bin/sh\ncommand alias emit='cat <<EOF'\nemit\n# payload\nEOF\n"
	if err := os.WriteFile(filepath.Join(root, "c.sh"), []byte(posix), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := Delete(root, []Target{{File: "c.sh", Line: 4}}); err == nil {
		t.Fatal("deleting comments in a script that defines aliases should be refused")
	}
}


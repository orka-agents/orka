func TestPathAliasesAndExtensionlessScripts(t *testing.T) {
	root := newRepo(t)
	if err := os.MkdirAll(filepath.Join(root, "api"), 0o700); err != nil {
		t.Fatal(err)
	}
	files := map[string]string{
		"api/t_types.go": "package api\n\n// Thing is documented for CRDs.\ntype Thing struct{}\n",
		"check":          "#!/usr/bin/env bash\n# real\necho hi\n",
		"tool":           "#!/usr/bin/python3\n# real\nprint(1)\n",
		"README":         "# heading\n",
	}
	for name, body := range files {
		if err := os.WriteFile(filepath.Join(root, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := Delete(root, []Target{{File: "./api/t_types.go", Line: 3}}); err == nil {
		t.Fatal("an api/ type doc reached through ./ must stay exempt")
	}
	if err := Delete(root, []Target{{File: "../x.go", Line: 1}}); err == nil {
		t.Fatal("targets outside the repository must be rejected")
	}
	for name, want := range map[string]string{"check": langShell, "tool": langPython, "README": ""} {
		if got := fileLanguage(filepath.Join(root, name), name); got != want {
			t.Errorf("fileLanguage(%s) = %q, want %q", name, got, want)
		}
	}
	assertTexts(t, mustScan(t, "check", files["check"]), "# real")
}


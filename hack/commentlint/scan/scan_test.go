func texts(comments []Comment) []string {
	out := make([]string, 0, len(comments))
	for _, c := range comments {
		out = append(out, c.Text)
	}
	return out
}

func newRepo(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	cmd := exec.Command("git", "init", "-q")
	cmd.Dir = root
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git init: %v %s", err, out)
	}
	return root
}

func mustScan(t *testing.T, name, src string) []Comment {
	t.Helper()
	root := newRepo(t)
	if err := os.WriteFile(filepath.Join(root, name), []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	got, err := Scan(root, name)
	if err != nil {
		t.Fatal(err)
	}
	return got
}

func assertTexts(t *testing.T, got []Comment, want ...string) {
	t.Helper()
	if strings.Join(texts(got), "|") != strings.Join(want, "|") {
		t.Fatalf("comments = %q, want %q", texts(got), want)
	}
}


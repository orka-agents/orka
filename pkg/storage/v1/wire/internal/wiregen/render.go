package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/orka-agents/orka/pkg/storage/v1/wire/storagepb"
)

const (
	storagepbPath = "github.com/orka-agents/orka/pkg/storage/v1/wire/storagepb"
	wirePath      = "github.com/orka-agents/orka/pkg/storage/v1/wire"
	header        = "// Code generated by wiregen from the orka.storage.v1 Go contract and wire descriptors. DO NOT EDIT.\n\n"
)

// goFile accumulates one generated Go file and its imports.
type goFile struct {
	pkg     string
	imports map[string]string
	body    bytes.Buffer
	names   int
}

func newGoFile(pkg string) *goFile {
	return &goFile{pkg: pkg, imports: map[string]string{}}
}

func (f *goFile) use(path, name string) string {
	f.imports[path] = name
	return name
}

func (f *goFile) printf(layout string, args ...any) {
	fmt.Fprintf(&f.body, layout, args...)
}

// fresh returns a new local variable name.
func (f *goFile) fresh(prefix string) string {
	f.names++
	return fmt.Sprintf("%s%d", prefix, f.names)
}

// typeString renders t, importing the packages it names.
func (f *goFile) typeString(t types.Type) string {
	return types.TypeString(t, func(pkg *types.Package) string {
		if pkg.Path() == contractPath {
			return f.use(contractPath, "storagev1")
		}
		return f.use(pkg.Path(), pkg.Name())
	})
}

func (f *goFile) source() ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(header)
	fmt.Fprintf(&out, "package %s\n\n", f.pkg)
	if len(f.imports) > 0 {
		paths := make([]string, 0, len(f.imports))
		for path := range f.imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		out.WriteString("import (\n")
		for _, path := range paths {
			name := f.imports[path]
			if name == lastElement(path) {
				fmt.Fprintf(&out, "\t%q\n", path)
			} else {
				fmt.Fprintf(&out, "\t%s %q\n", name, path)
			}
		}
		out.WriteString(")\n\n")
	}
	out.Write(f.body.Bytes())
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated %s code: %w\n%s", f.pkg, err, out.String())
	}
	return formatted, nil
}

func lastElement(path string) string {
	return path[strings.LastIndex(path, "/")+1:]
}

// render writes the generated files for a checked model.
func render(m *model) (map[string][]byte, error) {
	outputs := map[string][]byte{}
	mapping := newGoFile("wire")
	for _, rec := range m.records {
		renderRecord(mapping, rec)
	}
	service := newGoFile("wire")
	renderService(service, m)
	overlay := newGoFile("wiretest")
	renderOverlay(overlay, m)
	codecs := newGoFile("wire")
	renderCodecs(codecs, m)
	recorder := newGoFile("wire_test")
	renderRecorder(recorder, m)
	for name, file := range map[string]*goFile{
		"zz_generated.mapping.go":          mapping,
		"zz_generated.service.go":          service,
		"zz_generated.codecs_test.go":      codecs,
		"zz_generated.recorder_test.go":    recorder,
		"wiretest/zz_generated.overlay.go": overlay,
	} {
		source, err := file.source()
		if err != nil {
			return nil, err
		}
		outputs[name] = source
	}
	return outputs, nil
}

// goCamelCase returns the Go name protoc-gen-go gives a wire name.
func goCamelCase(name string) string {
	var out []byte
	for index := 0; index < len(name); index++ {
		c := name[index]
		switch {
		case c == '_' && index == 0:
			out = append(out, 'X')
		case c == '_' && index+1 < len(name) && isLower(name[index+1]):
		case c >= '0' && c <= '9':
			out = append(out, c)
		default:
			if isLower(c) {
				c -= 'a' - 'A'
			}
			out = append(out, c)
			for ; index+1 < len(name) && isLower(name[index+1]); index++ {
				out = append(out, name[index+1])
			}
		}
	}
	return string(out)
}

func isLower(c byte) bool { return c >= 'a' && c <= 'z' }

func wireField(field protoreflect.FieldDescriptor) string {
	return goCamelCase(string(field.Name()))
}

func wireMessage(f *goFile, message protoreflect.MessageDescriptor) string {
	return f.use(storagepbPath, "storagepb") + "." + goCamelCase(string(message.Name()))
}

func lowerFirst(name string) string {
	return strings.ToLower(name[:1]) + name[1:]
}

// renderRecord writes toWire<R> and fromWire<R>.
func renderRecord(f *goFile, rec *record) {
	goType := f.typeString(rec.goType)
	wireType := wireMessage(f, rec.desc)
	f.printf("func toWire%s(in %s) (*%s, error) {\n", rec.name, goType, wireType)
	f.printf("out := &%s{}\nvar err error\n", wireType)
	for _, field := range rec.fields {
		label := rec.name + "." + field.goName
		toWire(f, "out."+wireField(field.field), "in."+field.goName, field.conv, label, "return nil, err")
	}
	f.printf("return out, err\n}\n\n")

	f.printf("func fromWire%s(in *%s) (%s, error) {\n", rec.name, wireType, goType)
	f.printf("var out %s\nif in == nil {\nreturn out, nil\n}\nvar err error\n", goType)
	for _, field := range rec.fields {
		label := rec.name + "." + field.goName
		fromWire(f, "out."+field.goName, "in."+wireField(field.field), field.conv, label, "return out, err")
	}
	f.printf("return out, err\n}\n\n")
}

// toWire assigns the wire form of the Go value source to target.
func toWire(f *goFile, target, source string, c *conversion, label, onErr string) {
	switch c.kind {
	case convScalar:
		if c.cast {
			f.printf("%s = %s(%s)\n", target, c.wireType, source)
		} else {
			f.printf("%s = %s\n", target, source)
		}
	case convOptional:
		value := f.fresh("v")
		f.printf("if %s != nil {\n%s := %s(*%s)\n%s = &%s\n}\n", source, value, c.wireType, source, target, value)
	case convBytes:
		f.printf("%s = []byte(%s)\n", target, source)
	case convScalarMap:
		f.printf("%s = map[string]%s(%s)\n", target, c.wireType, source)
	case convTime:
		f.printf("if %s, err = timeToWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convNullableTime:
		f.printf("if %s, err = nullableTimeToWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convDuration:
		f.printf("%s = durationToWire(%s)\n", target, source)
	case convJSONAny:
		f.printf("if %s, err = jsonToWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convJSONMap:
		f.printf("if %s, err = jsonMapToWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convRawJSON:
		f.printf("if %s, err = rawJSONToWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convRecord:
		f.printf("if %s, err = toWire%s(%s); err != nil {\n%s\n}\n", target, c.record.name, source, onErr)
	case convRecordPointer:
		f.printf("if %s != nil {\nif %s, err = toWire%s(*%s); err != nil {\n%s\n}\n}\n", source, target, c.record.name, source, onErr)
	case convList:
		element := f.fresh("e")
		f.printf("for _, %s := range %s {\n", element, source)
		switch c.elem.kind {
		case convRecord:
			converted := f.fresh("w")
			f.printf("%s, err := toWire%s(%s)\nif err != nil {\n%s\n}\n", converted, c.elem.record.name, element, onErr)
			f.printf("%s = append(%s, %s)\n", target, target, converted)
		case convBytes:
			f.printf("%s = append(%s, []byte(%s))\n", target, target, element)
		default:
			f.printf("%s = append(%s, %s(%s))\n", target, target, c.elem.wireType, element)
		}
		f.printf("}\n")
	}
}

// fromWire assigns the Go form of the wire value source to target.
func fromWire(f *goFile, target, source string, c *conversion, label, onErr string) {
	// Render the Go type only where the code names it, so its package is
	// imported only when used.
	goType := func() string { return f.typeString(c.goType) }
	switch c.kind {
	case convScalar:
		if c.cast {
			f.printf("%s = %s(%s)\n", target, goType(), source)
		} else {
			f.printf("%s = %s\n", target, source)
		}
	case convOptional:
		value := f.fresh("v")
		elem := f.typeString(c.goType.(*types.Pointer).Elem())
		f.printf("if %s != nil {\n%s := %s(*%s)\n%s = &%s\n}\n", source, value, elem, source, target, value)
	case convBytes:
		// Protobuf decodes empty bytes as nil. A decoded bytes value is never
		// nil, so a present record keeps an empty value a provider may
		// require, as it would receive in process.
		f.printf("%s = %s(%s)\nif %s == nil {\n%s = %s{}\n}\n", target, goType(), source, target, target, goType())
	case convScalarMap:
		f.printf("%s = %s(%s)\n", target, goType(), source)
	case convTime:
		f.printf("if %s, err = timeFromWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convNullableTime:
		f.printf("if %s, err = nullableTimeFromWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convDuration:
		f.printf("if %s, err = durationFromWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convJSONAny:
		f.printf("if %s, err = jsonFromWire[any](%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convJSONMap:
		f.printf("if %s, err = jsonFromWire[map[string]any](%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convRawJSON:
		f.printf("if %s, err = rawJSONFromWire(%s, %q); err != nil {\n%s\n}\n", target, source, label, onErr)
	case convRecord:
		f.printf("if %s, err = fromWire%s(%s); err != nil {\n%s\n}\n", target, c.record.name, source, onErr)
	case convRecordPointer:
		value := f.fresh("v")
		f.printf("if %s != nil {\nvar %s %s\nif %s, err = fromWire%s(%s); err != nil {\n%s\n}\n%s = &%s\n}\n",
			source, value, f.typeString(c.record.goType), value, c.record.name, source, onErr, target, value)
	case convList:
		element := f.fresh("e")
		elemType := f.typeString(c.elem.goType)
		f.printf("if len(%s) > 0 {\n%s = make(%s, 0, len(%s))\n}\n", source, target, goType(), source)
		f.printf("for _, %s := range %s {\n", element, source)
		switch c.elem.kind {
		case convRecord:
			converted := f.fresh("g")
			f.printf("%s, err := fromWire%s(%s)\nif err != nil {\n%s\n}\n", converted, c.elem.record.name, element, onErr)
			f.printf("%s = append(%s, %s)\n", target, target, converted)
		default:
			f.printf("%s = append(%s, %s(%s))\n", target, target, elemType, element)
		}
		f.printf("}\n")
	}
}

// zeroValue renders the zero value of t.
func zeroValue(f *goFile, t types.Type) string {
	switch underlying := t.Underlying().(type) {
	case *types.Basic:
		switch {
		case underlying.Info()&types.IsString != 0:
			return `""`
		case underlying.Info()&types.IsBoolean != 0:
			return "false"
		default:
			return "0"
		}
	case *types.Struct:
		return f.typeString(t) + "{}"
	default:
		return "nil"
	}
}

func kindName(kind storagepb.MethodKind) string {
	if kind == storagepb.MethodKind_METHOD_KIND_WRITE {
		return "KindWrite"
	}
	return "KindRead"
}

func streamName(stream streamShape) string {
	switch stream {
	case streamUpload:
		return "streamUpload"
	case streamDownload:
		return "streamDownload"
	case streamSnapshot:
		return "streamSnapshot"
	default:
		return "streamNone"
	}
}

// batchedName renders a snapshot RPC's batched path as the dotted wire field
// names.
func batchedName(method *rpcMethod) string {
	names := make([]string, 0, len(method.batched))
	for _, field := range method.batched {
		names = append(names, string(field.Name()))
	}
	return strings.Join(names, ".")
}

func contractName(contract string) string {
	switch contract {
	case contractState:
		return "storagev1.StateContract"
	case contractArtifacts:
		return "storagev1.ArtifactsContract"
	default:
		return `""`
	}
}

// responseVar names the decoded or built response in generated methods.
const responseVar = "wireResponse"

// reservedNames are locals of generated methods that a parameter must not
// shadow.
var reservedNames = map[string]bool{
	"client": true, "service": true, "overlay": true, "wireRequest": true, responseVar: true,
	"err": true, "callErr": true, "opts": true,
}

func paramName(name string) string {
	if reservedNames[name] {
		return name + "Arg"
	}
	return name
}

// renderService writes the method table, the client methods and the server
// handlers.
func renderService(f *goFile, m *model) {
	grpc := f.use("google.golang.org/grpc", "grpc")
	f.use(contractPath, "storagev1")
	f.printf("var (\n")
	for _, svc := range m.services {
		for _, method := range svc.methods {
			batched := ""
			if method.stream == streamSnapshot {
				batched = fmt.Sprintf(", batched: %q", batchedName(method))
			}
			f.printf("method%s = method{name: %q, fullName: %q, kind: %s, since: %d, stream: %s, contract: %s, callClass: %s%s}\n",
				method.name, method.name, "/"+string(svc.desc.FullName())+"/"+method.name, kindName(method.kind),
				method.since, streamName(method.stream), contractName(svc.contract), method.class, batched)
		}
	}
	f.printf(")\n\nvar methodsByFullName = map[string]*method{\n")
	for _, svc := range m.services {
		for _, method := range svc.methods {
			f.printf("method%s.fullName: &method%s,\n", method.name, method.name)
		}
	}
	f.printf("}\n\n")

	f.printf("// clientStubs holds one generated stub per service.\ntype clientStubs struct {\n")
	for _, svc := range m.services {
		f.printf("%s %s.%sClient\n", lowerFirst(svc.name), f.use(storagepbPath, "storagepb"), svc.name)
	}
	f.printf("}\n\nfunc newClientStubs(conn %s.ClientConnInterface) clientStubs {\nreturn clientStubs{\n", grpc)
	for _, svc := range m.services {
		f.printf("%s: storagepb.New%sClient(conn),\n", lowerFirst(svc.name), svc.name)
	}
	f.printf("}\n}\n\n")

	f.printf("// The Client implements every contract interface that has a wire service.\nvar (\n")
	for _, svc := range m.services {
		for _, iface := range svc.interfaces {
			f.printf("_ %s = (*Client)(nil)\n", f.typeString(iface.Type()))
		}
	}
	f.printf(")\n\n")

	for _, svc := range m.services {
		for _, method := range svc.methods {
			renderClientMethod(f, method)
		}
	}

	f.printf("func (s *Server) registerServices(registrar %s.ServiceRegistrar) {\n", grpc)
	for _, contract := range []string{contractBoth, contractState, contractArtifacts} {
		var registered []*service
		for _, svc := range m.services {
			if svc.contract == contract && !svc.optional {
				registered = append(registered, svc)
			}
		}
		if len(registered) == 0 {
			continue
		}
		provider := map[string]string{contractBoth: "s.dataset", contractState: "s.state", contractArtifacts: "s.artifacts"}[contract]
		if contract != contractBoth {
			f.printf("if %s != nil {\n", provider)
		}
		for _, svc := range registered {
			f.printf("storagepb.Register%sServer(registrar, &%sService{server: s, provider: %s})\n", svc.name, lowerFirst(svc.name), provider)
		}
		if contract != contractBoth {
			f.printf("}\n")
		}
	}
	for _, svc := range m.services {
		if svc.optional {
			f.printf("if provider := s.%sProvider(); provider != nil {\n", lowerFirst(svc.name))
			f.printf("storagepb.Register%sServer(registrar, &%sService{server: s, provider: provider})\n}\n",
				svc.name, lowerFirst(svc.name))
		}
	}
	f.printf("}\n\n")
	for _, svc := range m.services {
		if svc.optional {
			renderOptionalProvider(f, svc)
		}
		renderServer(f, svc)
	}
}

// serviceProvider renders the interface a service's provider implements.
func serviceProvider(f *goFile, svc *service) string {
	embedded := make([]string, 0, len(svc.interfaces))
	for _, iface := range svc.interfaces {
		embedded = append(embedded, f.typeString(iface.Type()))
	}
	return "interface {\n" + strings.Join(embedded, "\n") + "\n}"
}

// renderOptionalProvider writes the lookup of the provider that serves an
// optional service: the state provider when it implements every interface,
// else the artifacts provider when it does, else none.
func renderOptionalProvider(f *goFile, svc *service) {
	provider := serviceProvider(f, svc)
	f.printf("// %sProvider returns the provider that serves %s: the state provider when it\n", lowerFirst(svc.name), svc.desc.FullName())
	f.printf("// implements the service's interfaces, else the artifacts provider when it\n// does, else nil.\n")
	f.printf("func (s *Server) %sProvider() %s {\n", lowerFirst(svc.name), provider)
	f.printf("if provider, ok := s.state.(%s); ok {\nreturn provider\n}\n", provider)
	f.printf("if provider, ok := s.artifacts.(%s); ok {\nreturn provider\n}\nreturn nil\n}\n\n", provider)
}

func signature(f *goFile, method *rpcMethod) (params, args, results string) {
	paramList := make([]string, 0, 1+len(method.params))
	argList := make([]string, 0, 1+len(method.params))
	paramList = append(paramList, "ctx "+f.use("context", "context")+".Context")
	argList = append(argList, "ctx")
	for _, param := range method.params {
		name := paramName(param.goName)
		paramList = append(paramList, name+" "+f.typeString(param.goType))
		argList = append(argList, name)
	}
	resultList := make([]string, 0, len(method.results)+1)
	for _, result := range method.results {
		resultList = append(resultList, f.typeString(result.goType))
	}
	resultList = append(resultList, "error")
	results = strings.Join(resultList, ", ")
	if len(resultList) > 1 {
		results = "(" + results + ")"
	}
	return strings.Join(paramList, ", "), strings.Join(argList, ", "), results
}

func zeroResults(f *goFile, method *rpcMethod, errExpr string) string {
	values := make([]string, 0, len(method.results)+1)
	for _, result := range method.results {
		values = append(values, zeroValue(f, result.goType))
	}
	return strings.Join(append(values, errExpr), ", ")
}

func renderClientMethod(f *goFile, method *rpcMethod) {
	params, _, results := signature(f, method)
	request := wireMessage(f, method.desc.Input())
	stub := lowerFirst(method.service.name)
	f.printf("// %s calls %s.\n", method.name, method.desc.FullName())
	f.printf("func (client *Client) %s(%s) %s {\n", method.name, params, results)
	onErr := "return " + zeroResults(f, method, "err")
	if method.inline != nil {
		f.printf("wireRequest, err := toWire%s(%s)\nif err != nil {\n%s\n}\n", method.inline.name,
			paramName(method.params[0].goName), onErr)
	} else {
		f.printf("wireRequest := &%s{}\nvar err error\n", request)
		for _, param := range method.params {
			target := "wireRequest." + wireField(param.field)
			if param.since > method.since {
				f.printf("if client.serverRevision >= %d {\n", param.since)
			}
			toWire(f, target, paramName(param.goName), param.conv, method.name+"."+param.goName, onErr)
			if param.since > method.since {
				f.printf("}\n")
			}
		}
		f.printf("_ = err\n")
	}
	switch method.stream {
	case streamUpload, streamDownload, streamSnapshot:
		helper, open := "upload", fmt.Sprintf("client.bulk.%s.%s(ctx, opts...)", stub, method.name)
		switch method.stream {
		case streamDownload:
			helper, open = "download", fmt.Sprintf("client.bulk.%s.%s(ctx, wireRequest, opts...)", stub, method.name)
		case streamSnapshot:
			helper, open = "snapshot", fmt.Sprintf("client.bulk.%s.%s(ctx, wireRequest, opts...)", stub, method.name)
		}
		f.printf("wireResponse := &%s{}\n", wireMessage(f, method.desc.Output()))
		f.printf("if err := client.%s(ctx, &method%s, wireRequest, wireResponse, "+
			"func(ctx context.Context, opts ...grpc.CallOption) (grpc.ClientStream, error) {\nreturn %s\n}); err != nil {\nreturn %s\n}\n",
			helper, method.name, open, zeroResults(f, method, "err"))
	default:
		callTarget := "_"
		if len(method.results) > 0 {
			f.printf("var wireResponse *%s\n", wireMessage(f, method.desc.Output()))
			callTarget = responseVar
		}
		f.printf("if err := client.invoke(ctx, &method%s, wireRequest, func(ctx context.Context, opts ...grpc.CallOption) error {\n", method.name)
		if callTarget == "_" {
			f.printf("_, callErr := client.stubs.%s.%s(ctx, wireRequest, opts...)\nreturn callErr\n", stub, method.name)
		} else {
			f.printf("var callErr error\nwireResponse, callErr = client.stubs.%s.%s(ctx, wireRequest, opts...)\nreturn callErr\n", stub, method.name)
		}
		f.printf("}); err != nil {\nreturn %s\n}\n", zeroResults(f, method, "err"))
	}
	names := make([]string, 0, len(method.results)+1)
	for _, result := range method.results {
		f.printf("var %s %s\n", result.goName, f.typeString(result.goType))
		fromWire(f, result.goName, responseVar+"."+wireField(result.field), result.conv, method.name+" result",
			"return "+zeroResults(f, method, fmt.Sprintf("client.responseError(&method%s, err)", method.name)))
		names = append(names, result.goName)
	}
	f.printf("return %s\n}\n\n", strings.Join(append(names, "nil"), ", "))
}

func renderServer(f *goFile, svc *service) {
	f.printf("// %sService serves %s from a provider.\n", lowerFirst(svc.name), svc.desc.FullName())
	f.printf("type %sService struct {\nstoragepb.Unimplemented%sServer\nserver *Server\nprovider %s\n}\n\n",
		lowerFirst(svc.name), svc.name, serviceProvider(f, svc))
	for _, method := range svc.methods {
		request := wireMessage(f, method.desc.Input())
		response := wireMessage(f, method.desc.Output())
		// fail returns an error from the handler: unary handlers also return
		// a nil response.
		fail := "return nil, %s"
		switch method.stream {
		case streamUpload:
			fail = "return %s"
			f.printf("func (service *%sService) %s(stream grpc.ClientStreamingServer[%s, %s]) error {\n",
				lowerFirst(svc.name), method.name, request, response)
			f.printf("ctx := stream.Context()\nwireRequest := &%s{}\n", request)
			f.printf("if err := service.server.receiveUpload(stream, &method%s, wireRequest); err != nil {\nreturn err\n}\n", method.name)
		case streamDownload, streamSnapshot:
			fail = "return %s"
			f.printf("func (service *%sService) %s(wireRequest *%s, stream grpc.ServerStreamingServer[%s]) error {\n",
				lowerFirst(svc.name), method.name, request, response)
			f.printf("ctx := stream.Context()\n")
		default:
			f.printf("func (service *%sService) %s(ctx context.Context, wireRequest *%s) (*%s, error) {\n",
				lowerFirst(svc.name), method.name, request, response)
		}
		f.printf("var err error\n")
		args := []string{"ctx"}
		for index, param := range method.params {
			name := fmt.Sprintf("a%d", index)
			if method.inline != nil {
				f.printf("var %s %s\nif %s, err = fromWire%s(wireRequest); err != nil {\n%s\n}\n", name,
					f.typeString(param.goType), name, method.inline.name, fmt.Sprintf(fail, "requestStatus(err)"))
			} else {
				f.printf("var %s %s\n", name, f.typeString(param.goType))
				fromWire(f, name, "wireRequest."+wireField(param.field), param.conv, method.name+"."+param.goName,
					fmt.Sprintf(fail, "requestStatus(err)"))
			}
			args = append(args, name)
		}
		var results []string
		for _, result := range method.results {
			f.printf("var %s %s\n", result.goName, f.typeString(result.goType))
			results = append(results, result.goName)
		}
		f.printf("%s = service.provider.%s(%s)\n", strings.Join(append(results, "err"), ", "), method.name, strings.Join(args, ", "))
		f.printf("if err != nil {\n%s\n}\n", fmt.Sprintf(fail, fmt.Sprintf("service.server.providerError(ctx, &method%s, err)", method.name)))
		f.printf("wireResponse := &%s{}\n", response)
		for _, result := range method.results {
			toWire(f, responseVar+"."+wireField(result.field), result.goName, result.conv, method.name+" result",
				fmt.Sprintf(fail, fmt.Sprintf("service.server.encodeError(ctx, &method%s, err)", method.name)))
		}
		if len(method.library) > 0 {
			f.printf("service.server.library%s(%s)\n", method.name, strings.Join(append([]string{responseVar}, results...), ", "))
		}
		switch method.stream {
		case streamUpload:
			f.printf("return stream.SendAndClose(wireResponse)\n}\n\n")
		case streamDownload:
			f.printf("return service.server.sendDownload(stream, &method%s, wireResponse)\n}\n\n", method.name)
		case streamSnapshot:
			f.printf("return service.server.sendSnapshot(stream, &method%s, wireResponse)\n}\n\n", method.name)
		default:
			f.printf("return wireResponse, nil\n}\n\n")
		}
	}
}

// renderOverlay writes the wiretest overlay: a state provider that sends
// every state.v1 method with a wire RPC through the client and serves the
// rest in process. An optional service is not part of state.v1, so the
// overlay leaves it out; its RPCs are tested through the client directly.
func renderOverlay(f *goFile, m *model) {
	storagev1 := f.use(contractPath, "storagev1")
	wire := f.use(wirePath, "wire")
	f.printf("// stateOverlay serves the contract families that have wire RPCs through the\n")
	f.printf("// client, and every other family from the in-process provider.\n")
	f.printf("type stateOverlay struct {\n%s.StateProvider\nclient *%s.Client\n}\n\n", storagev1, wire)
	for _, svc := range m.services {
		if svc.contract == contractArtifacts || svc.optional {
			continue
		}
		for _, method := range svc.methods {
			params, args, results := signature(f, method)
			f.printf("func (overlay stateOverlay) %s(%s) %s {\nreturn overlay.client.%s(%s)\n}\n\n",
				method.name, params, results, method.name, args)
		}
	}
}

// renderCodecs writes the test table of record conversions, so the
// round-trip and fuzz tests cover every record without a hand-kept list.
func renderCodecs(f *goFile, m *model) {
	reflect := f.use("reflect", "reflect")
	proto := f.use("google.golang.org/protobuf/proto", "proto")
	f.printf("var recordCodecs = []recordCodec{\n")
	for _, rec := range m.records {
		goType := f.typeString(rec.goType)
		wireType := wireMessage(f, rec.desc)
		f.printf("{\nname: %q,\ngoType: %s.TypeFor[%s](),\n", rec.name, reflect, goType)
		f.printf("newWire: func() %s.Message { return &%s{} },\n", proto, wireType)
		f.printf("toWire: func(value any) (%s.Message, error) { return toWire%s(value.(%s)) },\n", proto, rec.name, goType)
		f.printf("fromWire: func(message %s.Message) (any, error) { return fromWire%s(message.(*%s)) },\n},\n",
			proto, rec.name, wireType)
	}
	f.printf("}\n")
}

// renderRecorder writes the test provider that records the arguments of
// every method with a wire RPC and returns preset results.
func renderRecorder(f *goFile, m *model) {
	f.printf("// wireMethods lists every contract method with a wire RPC.\nvar wireMethods = []string{\n")
	for _, svc := range m.services {
		for _, method := range svc.methods {
			f.printf("%q,\n", method.name)
		}
	}
	f.printf("}\n\n")
	for _, svc := range m.services {
		for _, method := range svc.methods {
			params, _, results := signature(f, method)
			args := make([]string, 0, 2+len(method.params))
			args = append(args, "ctx", fmt.Sprintf("%q", method.name))
			for _, param := range method.params {
				args = append(args, paramName(param.goName))
			}
			f.printf("func (p *recordingProvider) %s(%s) %s {\n", method.name, params, results)
			f.printf("results, err := p.called(%s)\n", strings.Join(args, ", "))
			values := make([]string, 0, len(method.results)+1)
			for index, result := range method.results {
				values = append(values, fmt.Sprintf("resultAs[%s](results, %d)", f.typeString(result.goType), index))
			}
			if len(values) == 0 {
				f.printf("_ = results\n")
			}
			f.printf("return %s\n}\n\n", strings.Join(append(values, "err"), ", "))
		}
	}
}
